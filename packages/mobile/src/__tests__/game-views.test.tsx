import { fireEvent, render, screen } from "@testing-library/react-native";

import GameScreen from "@/app/game";
import { useGameStore } from "@/lib/store";
import { player, startLiveGame } from "@/test/gameFixtures";

jest.mock("expo-router", () => ({
  useRouter: () => ({ push: jest.fn(), replace: jest.fn(), back: jest.fn(), canGoBack: () => true }),
}));
jest.mock("expo-keep-awake", () => ({ useKeepAwake: jest.fn() }));

const state = () => useGameStore.getState();

async function openTab(name: "Live" | "Stats" | "Scoresheet") {
  await fireEvent.press(screen.getByRole("tab", { name }));
  expect(screen.getByRole("tab", { name })).toBeSelected();
}

beforeEach(() => {
  startLiveGame();
  const jordan = player("home", "10").id;
  state().recordScore("home", jordan, "3pt", true);
  state().recordScore("home", jordan, "2pt", false);
  state().recordScore("home", jordan, "ft", true);
  state().recordStat("home", jordan, "rebound-def");
  state().recordStat("home", jordan, "assist");
  for (let i = 0; i < 5; i++) state().recordFoul("away", player("away", "30").id, "personal");
  state().recordTeamScoreAdjust("away", 5, "missing jersey");
});

describe("Stats tab", () => {
  it("shows each player's box score line and the team totals", async () => {
    await render(<GameScreen />);
    await openTab("Stats");

    expect(
      screen.getByLabelText(
        "Jordan, number 10: 4 points, 1 of 2 field goals, 1 of 1 threes, 1 of 1 free throws, " +
          "1 rebounds, 1 assists, 0 steals, 0 blocks, 0 turnovers, 0 fouls",
      ),
    ).toBeOnTheScreen();
    expect(screen.getByLabelText(/^Central total: 4 points, 1 of 2 field goals/)).toBeOnTheScreen();
    expect(screen.getByText("Jordan * C")).toBeOnTheScreen();
    expect(screen.getByText("Harper")).toBeOnTheScreen();
  });

  it("marks a fouled-out player and counts timeouts and team fouls", async () => {
    await render(<GameScreen />);
    await openTab("Stats");

    expect(screen.getByLabelText(/^Bird, number 30: .*5 fouls, fouled out$/)).toBeOnTheScreen();
    expect(screen.getByText("Team fouls 5")).toBeOnTheScreen();
    expect(screen.getAllByText("Timeouts 0/5")).toHaveLength(2);
    // The console isn't shown on this tab.
    expect(screen.queryByRole("button", { name: "Start clock" })).toBeNull();
  });
});

describe("Scoresheet tab", () => {
  it("adds up points per period, score awards included", async () => {
    await render(<GameScreen />);
    await openTab("Scoresheet");

    expect(screen.getByLabelText("Central: 1st 4, 2nd 0, 3rd 0, 4th 0. Final 4")).toBeOnTheScreen();
    expect(screen.getByLabelText("Eastridge: 1st 5, 2nd 0, 3rd 0, 4th 0. Final 5")).toBeOnTheScreen();
    expect(screen.getByLabelText("Eastridge totals: 5 points, 5 fouls")).toBeOnTheScreen();
    expect(
      screen.getByLabelText("Jordan, number 10: 4 points, 1 rebounds, 1 assists, 0 fouls"),
    ).toBeOnTheScreen();
  });

  it("names the competition and venue, with placeholders until they're set", async () => {
    const view = await render(<GameScreen />);
    await openTab("Scoresheet");
    expect(screen.getByRole("header", { name: "Untitled competition" })).toBeOnTheScreen();
    expect(screen.getByText("Venue not specified")).toBeOnTheScreen();
    expect(screen.getAllByText("Coach: —")).toHaveLength(2);
    expect(screen.getByText("Crew chief")).toBeOnTheScreen();
    expect(screen.getByText(/^Generated by theStats/)).toBeOnTheScreen();

    state().setSettings({ competition: "Spring League", venue: "Community Arena" });
    state().setTeam("home", { coach: "Phil" });
    await view.rerender(<GameScreen />);
    expect(screen.getByRole("header", { name: "Spring League" })).toBeOnTheScreen();
    expect(screen.getByText("Community Arena")).toBeOnTheScreen();
    expect(screen.getByText("Coach: Phil")).toBeOnTheScreen();
  });

  it("adds a column for overtime", async () => {
    useGameStore.setState({ currentPeriod: 5 });
    await render(<GameScreen />);
    await openTab("Scoresheet");
    // The scoreboard's period and the sheet's new column.
    expect(screen.getAllByText("OT")).toHaveLength(2);
    expect(screen.getByLabelText(/^Central: 1st 4, 2nd 0, 3rd 0, 4th 0, OT 0\. Final 4$/)).toBeOnTheScreen();
  });
});

describe("tabs", () => {
  it("goes back to the console from another tab", async () => {
    await render(<GameScreen />);
    await openTab("Scoresheet");
    expect(screen.queryByRole("button", { name: "Start clock" })).toBeNull();
    await openTab("Live");
    expect(screen.getByRole("button", { name: "Start clock" })).toBeOnTheScreen();
    expect(screen.getByRole("tab", { name: "Stats" })).not.toBeSelected();
  });
});

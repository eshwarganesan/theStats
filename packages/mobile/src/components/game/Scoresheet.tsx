import { computePeriodScores, formatPeriod, type Side, type Team } from "@thestats/core";
import { useMemo } from "react";
import { ScrollView, Text, View } from "react-native";

import { cx } from "@/lib/cx";
import { useGame } from "@/lib/gameContext";
import { useGameStats } from "@/lib/useGameStats";

const TABULAR = { fontVariant: ["tabular-nums" as const] };
const EYEBROW = "text-xs uppercase tracking-widest text-ink-muted";

/**
 * The official-style scoresheet, laid out like web's (and a paper FIBA
 * sheet): competition and venue, points per period, each team's players,
 * and lines for the officials' signatures.
 */
export function Scoresheet() {
  const homeTeam = useGame((s) => s.homeTeam);
  const awayTeam = useGame((s) => s.awayTeam);
  const settings = useGame((s) => s.settings);
  const events = useGame((s) => s.events);
  const currentPeriod = useGame((s) => s.currentPeriod);
  const periodScores = useMemo(
    () => computePeriodScores(events, settings.periods, currentPeriod),
    [events, settings.periods, currentPeriod],
  );

  return (
    <View className="gap-8 rounded-xl border border-surface-border bg-surface-elevated p-5 md:p-8">
      <View className="flex-row flex-wrap items-start justify-between gap-2 border-b-2 border-surface-border pb-4">
        <View className="shrink gap-1">
          <Text className={EYEBROW}>Official digital scoresheet</Text>
          <Text accessibilityRole="header" className="text-3xl font-bold text-ink">
            {settings.competition || "Untitled competition"}
          </Text>
          <Text className="text-sm text-ink-muted">{settings.venue || "Venue not specified"}</Text>
        </View>
        <View className="items-end gap-1">
          <Text className={EYEBROW}>Format</Text>
          <Text className="text-2xl font-bold text-ink">{settings.format}</Text>
        </View>
      </View>

      <View className="gap-2">
        <Text accessibilityRole="header" className={EYEBROW}>
          Points by period
        </Text>
        <ScrollView horizontal contentContainerClassName="min-w-full flex-col">
          <View className="flex-row border-b border-surface-border py-2">
            <Text className="w-48 px-3 text-xs uppercase text-ink-dim">Team</Text>
            {periodScores.home.map((_, i) => (
              <Text key={i} className="w-16 text-center text-xs uppercase text-ink-dim">
                {formatPeriod(i + 1, settings.periods)}
              </Text>
            ))}
            <Text className="w-20 text-center text-xs uppercase text-accent">Final</Text>
          </View>
          <PeriodRow team={homeTeam} scores={periodScores.home} periods={settings.periods} />
          <PeriodRow team={awayTeam} scores={periodScores.away} periods={settings.periods} />
        </ScrollView>
      </View>

      <View className="gap-8 lg:flex-row">
        <TeamBlock side="home" />
        <TeamBlock side="away" />
      </View>

      <View className="-mx-3 flex-row flex-wrap">
        {["Scorekeeper", "Assistant scorekeeper", "Timekeeper", "Crew chief"].map((role) => (
          <View key={role} className="w-1/2 px-3 pb-6 md:w-1/4">
            <View className="h-10 border-b border-ink-dim/40" />
            <Text className={cx(EYEBROW, "mt-2")}>{role}</Text>
          </View>
        ))}
      </View>

      <Text className="text-center text-xs text-ink-dim">
        Generated by theStats · {new Date().toLocaleString()}
      </Text>
    </View>
  );
}

function PeriodRow({ team, scores, periods }: { team: Team; scores: number[]; periods: number }) {
  const final = scores.reduce((a, b) => a + b, 0);
  const spoken = scores.map((s, i) => `${formatPeriod(i + 1, periods)} ${s}`).join(", ");
  return (
    <View
      accessible
      accessibilityLabel={`${team.name}: ${spoken}. Final ${final}`}
      className="flex-row items-center border-b border-surface-border/40 py-2"
    >
      <View className="w-48 flex-row items-center gap-2 px-3">
        <View className="h-2 w-2" style={{ backgroundColor: team.color }} />
        <Text className="shrink text-ink" numberOfLines={1}>
          {team.name}
        </Text>
      </View>
      {scores.map((s, i) => (
        <Text key={i} className="w-16 text-center text-ink-muted" style={TABULAR}>
          {s}
        </Text>
      ))}
      <Text className="w-20 text-center text-xl font-bold text-accent" style={TABULAR}>
        {final}
      </Text>
    </View>
  );
}

function TeamBlock({ side }: { side: Side }) {
  const team = useGame((s) => (side === "home" ? s.homeTeam : s.awayTeam));
  const stats = useGameStats()[side];

  return (
    <View className={cx("flex-1 gap-3 border-l-4 pl-4", side === "home" ? "border-l-home" : "border-l-away")}>
      <View className="gap-0.5">
        <Text className={EYEBROW}>{team.tag || side}</Text>
        <Text accessibilityRole="header" className="text-2xl font-bold text-ink">
          {team.name}
        </Text>
        <Text className="text-xs text-ink-muted">Coach: {team.coach || "—"}</Text>
      </View>
      <ScrollView horizontal contentContainerClassName="min-w-full flex-col">
        <View className="flex-row border-b border-surface-border py-1">
          <Cell head width="w-10" text="#" />
          <Cell head width="w-40" text="Player" align="left" />
          {["PTS", "FG", "3P", "FT", "R", "A", "PF"].map((h) => (
            <Cell key={h} head text={h} />
          ))}
        </View>
        {team.roster.map((p) => {
          const line = stats.players.find((s) => s.playerId === p.id);
          if (!line) return null;
          return (
            <View
              key={p.id}
              accessible
              accessibilityLabel={`${p.name}, number ${p.number}: ${line.points} points, ${line.rebounds} rebounds, ${line.assists} assists, ${line.fouls} fouls`}
              className="flex-row border-b border-surface-border/30 py-1"
            >
              <Cell width="w-10" text={p.number} />
              <Cell width="w-40" text={`${p.name}${p.isCaptain ? " C" : ""}`} align="left" strong />
              <Cell text={String(line.points)} strong />
              <Cell text={`${line.fgMade}/${line.fgAttempted}`} />
              <Cell text={`${line.threePtMade}/${line.threePtAttempted}`} />
              <Cell text={`${line.ftMade}/${line.ftAttempted}`} />
              <Cell text={String(line.rebounds)} />
              <Cell text={String(line.assists)} />
              <Cell text={String(line.fouls)} />
            </View>
          );
        })}
        <View
          accessible
          accessibilityLabel={`${team.name} totals: ${stats.points} points, ${stats.totalFouls} fouls`}
          className="flex-row border-t-2 border-surface-border py-2"
        >
          <Cell width="w-10" text="" />
          <Cell width="w-40" text="Totals" align="left" />
          <Cell text={String(stats.points)} accent />
          <Cell width="w-60" text="" />
          <Cell text={String(stats.totalFouls)} />
        </View>
      </ScrollView>
    </View>
  );
}

function Cell({
  text,
  width = "w-12",
  align = "right",
  head = false,
  strong = false,
  accent = false,
}: {
  text: string;
  width?: string;
  align?: "left" | "right";
  head?: boolean;
  strong?: boolean;
  accent?: boolean;
}) {
  return (
    <Text
      className={cx(
        width,
        "px-1 text-xs",
        align === "left" ? "text-left" : "text-right",
        head ? "uppercase text-ink-dim" : accent ? "text-base font-bold text-accent" : strong ? "text-ink" : "text-ink-muted",
      )}
      numberOfLines={1}
      style={TABULAR}
    >
      {text}
    </Text>
  );
}
